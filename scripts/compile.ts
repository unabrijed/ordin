import { readFileSync, mkdirSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const solc = require('solc') as {
  compile(input: string, callbacks: { import(path: string): { contents?: string; error?: string } }): string;
  version(): string;
};
function sources(dir: string): Record<string, { content: string }> {
  return Object.assign({}, ...readdirSync(dir, { withFileTypes: true }).map(entry => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? sources(path) : entry.name.endsWith('.sol') ? { [path]: { content: readFileSync(path, 'utf8') } } : {};
  }));
}
const input = { language: 'Solidity', sources: sources('contracts'), settings: {
  optimizer: { enabled: true, runs: 200 }, evmVersion: 'prague',
  outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
} };
const output = JSON.parse(solc.compile(JSON.stringify(input), { import(path) {
  try {
    const contents = readFileSync(require.resolve(path), 'utf8');
    input.sources[path] = { content: contents };
    return { contents };
  }
  catch { return { error: `Import not found: ${path}` }; }
} }));
for (const error of output.errors ?? []) console.error(error.formattedMessage);
if (output.errors?.some((error: { severity: string }) => error.severity === 'error')) process.exit(1);
mkdirSync('artifacts', { recursive: true });
writeFileSync('artifacts/compiler-input.json', JSON.stringify(input, null, 2));
for (const file of Object.keys(input.sources)) {
  for (const [name, artifact] of Object.entries(output.contracts[file] ?? {}) as [string, any][]) {
    writeFileSync(`artifacts/${name}.json`, JSON.stringify({ abi: artifact.abi, bytecode: `0x${artifact.evm.bytecode.object}`, compiler: solc.version() }, null, 2));
    if (name === 'Ordin') {
      writeFileSync('sdk/abi.ts', `// Generated by yarn compile.\nexport const ordinAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
    }
  }
}
console.log(`Compiled Ordin and test fixtures with ${solc.version()}.`);
